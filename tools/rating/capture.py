"""The pictures raters rate, and the features of exactly those pictures.

One headless Chromium read of each page on the corpus list
(`tools/evaluation/collect_corpus.STARTER_LIST`), driven into the same state
the corpus measured it in — a modal open, a calendar open — and photographed
at the frozen 1280x800 viewport, the visible part only, at device scale 1.

    python -m tools.rating.capture              # replicas started if not up
    python -m tools.rating.capture --only pypi-org www-bbc-co-uk-news
                                                # just these, into the manifest

**Scrollbars hidden.** A classic scrollbar takes 17px from the layout — the
host lays scrollable pages out at 1263px (STATUS.md) — and a rater would be
judging a scrollbar the product never shows the person. Headless Chromium
already lays pages out at the full 1280 with none, measured on 2026-09-25 in
both headless modes with and without the flag; `--hide-scrollbars` and the
style below are there so that stays true on a Chromium that does otherwise.
Each row records the layout width the page actually got, so a page that kept
a scrollbar would show in the manifest as less than 1280.

**Read once, then frozen.** Live pages change; ratings of two different
pictures of "bbc.co.uk" are not ratings of one stimulus. Every row records the
picture's sha256 and when it was taken, and every rating records the hash of
the picture it was given for (`tools/rating/serve.py`). Re-capturing makes a
new stimulus set, and the manifest says so.

Writes `data/rating/pages/*.png` (not committed: pictures of other people's
sites, regenerated by this command) and `data/rating/pages.json` (committed:
the list, the states and the hashes). Read-only, like the corpus collection
it reuses: nothing is submitted anywhere.

**The pictures and the corpus are one run** (since 2026-10-03). Until then they
were two: the pictures of 2026-09-25 and features re-collected on 2026-09-30,
so for a live page the features described a page five days newer than the one
rated. Now each page is loaded once, driven into its state, its features read
and its picture taken moments apart from the same page, and this writes
`data/corpus.json` as well — its headless half from those same reads, its host
half from the Electron host straight after. Both files carry the run's id and
date, on the file and on every row, so the estimator can check a picture and
its features came from the same run (`backend/estimator/train.py`).

    .\\run.ps1 registration                  # the host, for the corpus's host half
    python -m tools.rating.capture            # every page: pictures and corpus
    python -m tools.rating.capture --headless-only   # without the host half
"""

from __future__ import annotations

import asyncio
import hashlib
import json
import re
import sys
import time
from pathlib import Path

from playwright.async_api import Error as PlaywrightError
from playwright.async_api import async_playwright

from tools.evaluation.collect_corpus import (
    LOAD_TIMEOUT_MS,
    SETTLE_MS,
    STARTER_LIST,
    UA,
    features_now,
    in_host,
    name_of,
    replicas_running,
    reset,
    write_corpus,
)

REPO = Path(__file__).resolve().parents[2]
OUT = REPO / "data" / "rating"
PAGES = OUT / "pages"
MANIFEST = OUT / "pages.json"
VIEWPORT = {"width": 1280, "height": 800}

HIDE_SCROLLBARS = """
html, body { scrollbar-width: none !important; }
::-webkit-scrollbar { display: none !important; width: 0 !important; height: 0 !important; }
"""


def page_id(url: str, state: str) -> str:
    """A stable, readable name for one page in one state."""
    slug = re.sub(r"^https?://", "", url).rstrip("/")
    slug = re.sub(r"[^A-Za-z0-9]+", "-", slug).strip("-").lower()
    if state != "as it loads":
        slug += "--" + re.sub(r"[^A-Za-z0-9]+", "-", state).strip("-").lower()
    return slug[:90]


def new_run() -> dict:
    """One capture run: an id, and when it happened."""
    taken = time.strftime("%Y-%m-%dT%H:%M:%S%z")
    return {"id": hashlib.sha256(f"{taken}{time.perf_counter_ns()}".encode()).hexdigest()[:12],
            "taken_at": taken, "date": taken[:10]}


async def photograph(page, url: str, drive, kind: str, run: dict | None = None,
                     into: Path | None = None) -> tuple[dict, dict]:
    """The picture and the corpus row of one page, from one load. The picture
    goes to `into`, or to `PAGES` (the worked examples go elsewhere).

    The features are read and the picture taken in the same state, moments
    apart, after the drive and after the scrollbars are hidden — so the row
    describes the picture, and a live page cannot change between the two the
    way it did over the five days between 2026-09-25 and 2026-09-30.
    """
    run = run or new_run()
    state = name_of(drive)
    row = {"id": page_id(url, state), "url": url, "state": state, "kind": kind,
           "run": run["id"]}
    features = {"url": url, "state": state, "kind": kind, "run": run["id"]}
    try:
        await page.goto(url, wait_until="domcontentloaded", timeout=LOAD_TIMEOUT_MS)
        await page.wait_for_timeout(SETTLE_MS)
        if drive is not None:
            await drive(page)
            await page.wait_for_timeout(600)
        await page.add_style_tag(content=HIDE_SCROLLBARS)
        await page.wait_for_timeout(300)
        # The features first, then the picture straight after, of the page
        # as it is now — wherever the drive left it scrolled, which is what
        # both the picture and density (2026-09-30) are of.
        features = {**await features_now(page, url, drive, kind), "run": run["id"]}
        try:
            png = await page.screenshot(full_page=False)
        except PlaywrightError:
            # Chromium occasionally refuses one capture of a heavy page
            # ("Unable to capture screenshot"); a second is usually fine.
            await page.wait_for_timeout(1500)
            png = await page.screenshot(full_page=False)
        path = (into or PAGES) / f"{row['id']}.png"
        path.write_bytes(png)
        row.update({
            "file": path.name,
            "sha256": hashlib.sha256(png).hexdigest(),
            "layout_width": await page.evaluate("document.documentElement.clientWidth"),
            "title": (await page.title())[:80],
            "captured_at": time.strftime("%Y-%m-%dT%H:%M:%S%z"),
        })
    except PlaywrightError as refused:
        await reset(page)
        row["error"] = f"{type(refused).__name__}: {str(refused)[:120]}"
        features = {**features, "error": row["error"]}
    return row, features


async def capture(pages: list[tuple] = STARTER_LIST, run: dict | None = None
                  ) -> tuple[list[dict], list[dict]]:
    """Every page's picture and headless corpus row, from one load each."""
    run = run or new_run()
    PAGES.mkdir(parents=True, exist_ok=True)
    async with async_playwright() as playwright:
        browser = await playwright.chromium.launch(args=["--hide-scrollbars"])
        # `bypass_csp`: a page whose Content Security Policy forbids inline
        # styles (pypi.org, gov.uk) would otherwise refuse the scrollbar style
        # and fail the capture. Nothing else about the page changes.
        context = await browser.new_context(user_agent=UA, viewport=VIEWPORT,
                                            device_scale_factor=1, bypass_csp=True)
        page = await context.new_page()
        rows, headless = [], []
        for url, drive, kind in pages:
            row, features = await photograph(page, url, drive, kind, run)
            rows.append(row)
            headless.append(features)
            said = row.get("error") or f"{row['file']} (layout {row['layout_width']}px)"
            print(f"  {row['id'][:60]:<60} {said}", flush=True)
        await browser.close()
    return rows, headless


def main() -> None:
    for stream in (sys.stdout, sys.stderr):
        if hasattr(stream, "reconfigure"):
            stream.reconfigure(encoding="utf-8", errors="replace")
    headless_only = "--headless-only" in sys.argv
    argv = [a for a in sys.argv if a != "--headless-only"]
    only = set(argv[argv.index("--only") + 1:]) if "--only" in argv else None
    pages = STARTER_LIST
    if only:
        pages = [entry for entry in STARTER_LIST if page_id(entry[0], name_of(entry[1])) in only]
        missing = only - {page_id(url, name_of(drive)) for url, drive, _ in pages}
        if missing:
            raise SystemExit(f"not on the corpus list: {sorted(missing)}")
    if only:
        # A partial run would leave pictures and features from two runs side
        # by side, which is what this command exists to stop.
        raise SystemExit("--only is not supported since 2026-10-03: pictures and "
                         "features are captured together, all pages in one run.")
    run = new_run()
    print(f"run {run['id']}, {run['taken_at']}", flush=True)

    async def both() -> tuple[list[dict], list[dict], list[dict]]:
        rows, headless = await capture(pages, run)
        host = [] if headless_only else await in_host(pages)
        return rows, headless, [{**r, "run": run["id"]} for r in host]

    with replicas_running():
        rows, headless, host = asyncio.run(both())
    ids = [row["id"] for row in rows]
    duplicate = {i for i in ids if ids.count(i) > 1}
    if duplicate:
        raise SystemExit(f"two pages share an id: {sorted(duplicate)}")
    MANIFEST.write_text(json.dumps({
        "run": run, "viewport": VIEWPORT, "device_scale_factor": 1, "scrollbars": "hidden",
        "corpus": "data/corpus.json, the same run",
        "pages": rows,
    }, indent=2) + "\n", encoding="utf-8")
    write_corpus(pages, headless, host, run=run,
                 pictures="data/rating/pages.json, the same run")
    failed = [row for row in rows if "error" in row]
    print(f"{len(rows) - len(failed)} of {len(rows)} pages captured; "
          f"{len(failed)} failed; manifest {MANIFEST}; run {run['id']} on {run['date']}")


if __name__ == "__main__":
    main()
